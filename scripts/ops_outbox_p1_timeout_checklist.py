"""Markdown checklist for P1 inactive orphan NA rows with timeout error bucket (C028)."""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import sys
from pathlib import Path

import structlog

from scripts.ops_json_cli import quiet_sqlalchemy_logs

logger = structlog.get_logger(__name__)
ROOT = Path(__file__).resolve().parents[1]

OPERATOR_HINT = (
    "Legacy proposal_approval on inactive telegram_pending. "
    "Verify Telegram UI; reconcile delivery before any reissue. "
    "Do not mass-reset to pending."
)


def _require_database_url() -> None:
    if not (os.environ.get("DATABASE_URL") or os.environ.get("JOBPILOT_WORKING_DATABASE_URL")):
        print("Set DATABASE_URL or JOBPILOT_WORKING_DATABASE_URL", file=sys.stderr)
        raise SystemExit(2)


def _render(rows: list[dict], database_name: str) -> str:
    """Legacy helper kept for tests importing _render."""
    lines = [
        "# Outbox P1 — inactive orphan NA (timeout bucket only)",
        "",
        f"Database: `{database_name}`",
        f"Rows: **{len(rows)}**",
        "",
        f"> {OPERATOR_HINT}",
        "",
    ]
    for row in rows:
        lines.append(
            f"- [ ] outbox `{row.get('outbox_id')}` kind `{row.get('kind')}` "
            f"ref `{row.get('reference_id')}` telegram_msg {row.get('telegram_message_id') or '—'}"
        )
    lines.extend(["", "---", "Generated by `scripts/ops_outbox_p1_timeout_checklist.py` (read-only)."])
    return "\n".join(lines)


async def run_checklist(*, as_json: bool, error_bucket: str) -> int:
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    from scripts.ops_pending_outbox_crosscheck import run_crosscheck

    crosscheck = await run_crosscheck()
    inactive = crosscheck.get("needs_attention_outbox_for_inactive_pending") or []
    by_bucket = crosscheck.get("inactive_needs_attention_by_error_bucket") or {}
    if error_bucket == "all":
        filtered = inactive
        total = int(crosscheck.get("inactive_needs_attention_orphan_count") or len(filtered))
    else:
        filtered = [row for row in inactive if row.get("error_bucket") == error_bucket]
        total = int(by_bucket.get(error_bucket, len(filtered)))
    if as_json:
        print(
            json.dumps(
                {
                    "database_name": crosscheck.get("database_name"),
                    "error_bucket": error_bucket,
                    "inactive_orphan_count": total,
                    "rows": filtered,
                    "inactive_needs_attention_by_error_bucket": by_bucket,
                    "operator_hint": OPERATOR_HINT,
                },
                ensure_ascii=False,
                indent=2,
            )
        )
    else:
        title_bucket = error_bucket if error_bucket != "all" else "all buckets"
        lines = [
            "# Outbox P1 — inactive orphan NA",
            "",
            f"Database: `{crosscheck.get('database_name', '?')}`",
            f"Error bucket filter: **{title_bucket}**",
            f"Count: **{total}**",
            "",
            f"> {OPERATOR_HINT}",
            "",
        ]
        for row in filtered:
            lines.append(
                f"- [ ] outbox `{row.get('outbox_id')}` kind `{row.get('kind')}` "
                f"bucket `{row.get('error_bucket')}` ref `{row.get('reference_id')}` "
                f"telegram_msg {row.get('telegram_message_id') or '—'}"
            )
        lines.extend(["", "---", "Generated by `scripts/ops_outbox_p1_timeout_checklist.py` (read-only)."])
        print("\n".join(lines))
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true")
    parser.add_argument(
        "--error-bucket",
        default="timeout",
        choices=("timeout", "other", "lease_expired", "partial_delivery", "unknown", "all"),
        help="Filter inactive orphan NA rows (default: timeout)",
    )
    args = parser.parse_args()
    quiet_sqlalchemy_logs()
    _require_database_url()
    try:
        return asyncio.run(run_checklist(as_json=args.json, error_bucket=args.error_bucket))
    except Exception as exc:
        logger.error("p1 inactive checklist failed", error=str(exc))
        print(json.dumps({"error": str(exc)}, ensure_ascii=False))
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
