"""Markdown checklist for inbox_alert outbox needs_attention (telegram_inbox_pending refs)."""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import sys
from pathlib import Path

import structlog

from scripts.ops_json_cli import quiet_sqlalchemy_logs, rebind_async_engine

logger = structlog.get_logger(__name__)
ROOT = Path(__file__).resolve().parents[1]

OPERATOR_HINT = (
    "Inbox alert partial delivery / lease / timeout. "
    "Verify Telegram thread UI; reissue per operator-review-reissue — no blind resend."
)


def _require_database_url() -> None:
    if not (os.environ.get("DATABASE_URL") or os.environ.get("JOBPILOT_WORKING_DATABASE_URL")):
        print("Set DATABASE_URL or JOBPILOT_WORKING_DATABASE_URL", file=sys.stderr)
        raise SystemExit(2)


def _render(groups: list[dict], database_name: str, total: int) -> str:
    lines = [
        "# Outbox — inbox_alert needs_attention",
        "",
        f"Database: `{database_name}`",
        f"Rows (inbox_alert NA in triage groups): **{total}**",
        "",
        f"> {OPERATOR_HINT}",
        "",
    ]
    for group in groups:
        kind = group.get("kind", "?")
        bucket = group.get("error_bucket", "?")
        count = group.get("count", 0)
        lines.append(f"## {kind} / {bucket} ({count})")
        lines.append("")
        for item in group.get("items") or []:
            oid = item.get("outbox_id", "?")
            ref = item.get("reference_id") or "—"
            msg = item.get("telegram_message_id")
            lines.append(
                f"- [ ] outbox `{oid}` ref `{ref}` telegram_msg {msg if msg is not None else '—'}"
            )
        trunc = int(group.get("items_truncated") or 0)
        if trunc:
            lines.append(f"- … **{trunc}** more (raise inventory limit)")
        lines.append("")
    lines.append("---")
    lines.append("Generated by `scripts/ops_outbox_inbox_na_checklist.py` (read-only).")
    return "\n".join(lines)


async def run_checklist(*, as_json: bool, pending_limit: int) -> int:
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    await rebind_async_engine()
    from scripts.ops_notification_outbox_inventory import run_inventory

    inv = await run_inventory(pending_limit=pending_limit)
    ref_counts = inv.get("needs_attention_by_reference_type") or {}
    inbox_ref_total = int(ref_counts.get("telegram_inbox_pending", 0))
    groups = [
        g
        for g in inv.get("needs_attention_triage_groups") or []
        if g.get("kind") == "inbox_alert"
    ]
    if as_json:
        print(
            json.dumps(
                {
                    "database_name": inv.get("database_name"),
                    "inbox_alert_needs_attention_by_reference_type": inbox_ref_total,
                    "triage_groups": groups,
                    "operator_hint": OPERATOR_HINT,
                },
                ensure_ascii=False,
                indent=2,
            )
        )
    else:
        print(_render(groups, inv.get("database_name", "?"), inbox_ref_total))
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--pending-limit", type=int, default=50)
    args = parser.parse_args()
    quiet_sqlalchemy_logs()
    _require_database_url()
    try:
        return asyncio.run(
            run_checklist(as_json=args.json, pending_limit=max(1, args.pending_limit))
        )
    except Exception as exc:
        logger.error("inbox na checklist failed", error=str(exc))
        print(json.dumps({"error": str(exc)}, ensure_ascii=False))
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
