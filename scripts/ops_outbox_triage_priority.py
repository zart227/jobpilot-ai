"""Markdown triage queue: inactive orphan NA first, then active pending NA, then outbox groups."""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import sys
from pathlib import Path

import structlog

from scripts.ops_json_cli import quiet_sqlalchemy_logs

logger = structlog.get_logger(__name__)
ROOT = Path(__file__).resolve().parents[1]


def _require_database_url() -> None:
    if not (os.environ.get("DATABASE_URL") or os.environ.get("JOBPILOT_WORKING_DATABASE_URL")):
        print("Set DATABASE_URL or JOBPILOT_WORKING_DATABASE_URL", file=sys.stderr)
        raise SystemExit(2)


def _render(crosscheck: dict, inventory: dict) -> str:
    lines = [
        "# Outbox triage — priority queue",
        "",
        f"Database: `{crosscheck.get('database_name', inventory.get('database_name', '?'))}`",
        f"Outbox needs_attention total: **{inventory.get('needs_attention_total', 0)}**",
        f"Inactive pending orphan NA: **{crosscheck.get('inactive_needs_attention_orphan_count', 0)}**",
        f"Inactive by error bucket: `{crosscheck.get('inactive_needs_attention_by_error_bucket', {})}`",
        f"Active pending with NA: **{crosscheck.get('pending_with_outbox_needs_attention', 0)}**",
        "",
        "Do **not** mass-reset to `pending`. No auto-resend.",
        "",
        "## P1 — inactive `telegram_pending` (orphan NA)",
        "",
    ]
    inactive = crosscheck.get("needs_attention_outbox_for_inactive_pending") or []
    if not inactive:
        lines.append("_None in sample (count may still be >0 — re-run crosscheck)._")
    for row in inactive:
        lines.append(
            f"- [ ] outbox `{row.get('outbox_id')}` kind `{row.get('kind')}` "
            f"ref `{row.get('reference_id')}` telegram_msg {row.get('telegram_message_id') or '—'}"
        )
    lines.extend(["", "## P2 — active pending cards with outbox NA", ""])
    for row in crosscheck.get("active_pending_with_needs_attention") or []:
        lines.append(
            f"- [ ] pending `{row.get('pending_id')}` outbox NA ids {row.get('outbox_needs_attention_ids')}"
        )
    lines.extend(["", "## P3 — triage groups (timeout first)", ""])
    groups = list(inventory.get("needs_attention_triage_groups") or [])
    groups.sort(key=lambda g: (0 if g.get("error_bucket") == "timeout" else 1, g.get("kind") or ""))
    for group in groups:
        kind = group.get("kind", "?")
        bucket = group.get("error_bucket", "?")
        count = group.get("count", 0)
        lines.append(f"### {kind} / {bucket} ({count})")
        lines.append("")
        for item in group.get("items") or []:
            lines.append(
                f"- [ ] outbox `{item.get('outbox_id')}` ref `{item.get('reference_id') or '—'}`"
            )
        lines.append("")
    lines.append("---")
    lines.append("Generated by `scripts/ops_outbox_triage_priority.py` (read-only).")
    return "\n".join(lines)


async def run_priority(*, as_json: bool) -> int:
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    from scripts.ops_json_cli import rebind_async_engine
    from scripts.ops_notification_outbox_inventory import run_inventory
    from scripts.ops_pending_outbox_crosscheck import run_crosscheck

    await rebind_async_engine()
    crosscheck = await run_crosscheck()
    inventory = await run_inventory(pending_limit=50)
    if as_json:
        print(json.dumps({"crosscheck": crosscheck, "inventory_summary": {
            "needs_attention_total": inventory.get("needs_attention_total"),
            "needs_attention_by_reference_type": inventory.get("needs_attention_by_reference_type"),
        }}, ensure_ascii=False, indent=2))
    else:
        print(_render(crosscheck, inventory))
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()
    quiet_sqlalchemy_logs()
    _require_database_url()
    try:
        return asyncio.run(run_priority(as_json=args.json))
    except Exception as exc:
        logger.error("triage priority failed", error=str(exc))
        print(json.dumps({"error": str(exc)}, ensure_ascii=False))
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
