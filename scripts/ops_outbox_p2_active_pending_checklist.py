"""Markdown checklist for P2 active telegram_pending cards with outbox needs_attention (C030/C028)."""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import sys
from pathlib import Path

import structlog

from scripts.ops_json_cli import quiet_sqlalchemy_logs

logger = structlog.get_logger(__name__)
ROOT = Path(__file__).resolve().parents[1]

OPERATOR_HINT = (
    "Pending card still active; outbox row is needs_attention. "
    "Check Telegram UI for partial delivery; use review-reissue path — no blind resend to Kwork."
)


def _require_database_url() -> None:
    if not (os.environ.get("DATABASE_URL") or os.environ.get("JOBPILOT_WORKING_DATABASE_URL")):
        print("Set DATABASE_URL or JOBPILOT_WORKING_DATABASE_URL", file=sys.stderr)
        raise SystemExit(2)


def _render(rows: list[dict], database_name: str, total: int) -> str:
    lines = [
        "# Outbox P2 — active pending with outbox needs_attention",
        "",
        f"Database: `{database_name}`",
        f"Total active pending with NA: **{total}** (showing up to {len(rows)} in sample)",
        "",
        f"> {OPERATOR_HINT}",
        "",
    ]
    for row in rows:
        lines.append(
            f"- [ ] pending `{row.get('pending_id')}` outbox NA ids {row.get('outbox_needs_attention_ids')}"
        )
    lines.extend(["", "---", "Generated by `scripts/ops_outbox_p2_active_pending_checklist.py` (read-only)."])
    return "\n".join(lines)


async def run_checklist(*, as_json: bool) -> int:
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    from scripts.ops_pending_outbox_crosscheck import run_crosscheck

    crosscheck = await run_crosscheck()
    rows = crosscheck.get("active_pending_with_needs_attention") or []
    total = int(crosscheck.get("pending_with_outbox_needs_attention") or 0)
    if as_json:
        print(
            json.dumps(
                {
                    "database_name": crosscheck.get("database_name"),
                    "active_pending_with_outbox_needs_attention": total,
                    "rows": rows,
                    "operator_hint": OPERATOR_HINT,
                },
                ensure_ascii=False,
                indent=2,
            )
        )
    else:
        print(_render(rows, crosscheck.get("database_name", "?"), total))
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()
    quiet_sqlalchemy_logs()
    _require_database_url()
    try:
        return asyncio.run(run_checklist(as_json=args.json))
    except Exception as exc:
        logger.error("p2 active pending checklist failed", error=str(exc))
        print(json.dumps({"error": str(exc)}, ensure_ascii=False))
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
