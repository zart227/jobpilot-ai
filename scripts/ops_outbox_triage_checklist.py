"""Print operator markdown checklist from outbox needs_attention triage groups."""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import sys
from pathlib import Path

import structlog

logger = structlog.get_logger(__name__)

ROOT = Path(__file__).resolve().parents[1]


def _require_database_url() -> None:
    if not (os.environ.get("DATABASE_URL") or os.environ.get("JOBPILOT_WORKING_DATABASE_URL")):
        print("Set DATABASE_URL or JOBPILOT_WORKING_DATABASE_URL", file=sys.stderr)
        raise SystemExit(2)


def _render_markdown(report: dict) -> str:
    lines = [
        "# Outbox needs_attention — triage checklist",
        "",
        f"Database: `{report.get('database_name', '?')}`",
        f"Total needs_attention: **{report.get('needs_attention_total', 0)}**",
        "",
        "Do **not** mass-reset to `pending`. Verify Telegram UI before reissue.",
        "",
    ]
    for group in report.get("needs_attention_triage_groups") or []:
        kind = group.get("kind", "?")
        bucket = group.get("error_bucket", "?")
        count = group.get("count", 0)
        hint = group.get("operator_hint", "")
        lines.append(f"## {kind} / {bucket} ({count})")
        lines.append("")
        lines.append(f"> {hint}")
        lines.append("")
        for item in group.get("items") or []:
            oid = item.get("outbox_id", "?")
            ref = item.get("reference_id") or "—"
            msg = item.get("telegram_message_id")
            msg_s = str(msg) if msg is not None else "—"
            lines.append(
                f"- [ ] outbox `{oid}` ref `{ref}` telegram_msg {msg_s} "
                f"(created {item.get('created_at', '?')})"
            )
        truncated = int(group.get("items_truncated") or 0)
        if truncated:
            lines.append(f"- … and **{truncated}** more (re-run inventory with higher limit)")
        lines.append("")
    lines.append("---")
    lines.append("Generated by `scripts/ops_outbox_triage_checklist.py` (read-only).")
    return "\n".join(lines)


async def run_checklist(*, pending_limit: int, as_json: bool) -> int:
    if str(ROOT) not in sys.path:
        sys.path.insert(0, str(ROOT))
    from scripts.ops_notification_outbox_inventory import run_inventory

    report = await run_inventory(pending_limit=pending_limit)
    if as_json:
        print(json.dumps(report, ensure_ascii=False, indent=2))
    else:
        print(_render_markdown(report))
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pending-limit", type=int, default=50)
    parser.add_argument("--json", action="store_true", help="Emit full inventory JSON instead of markdown")
    args = parser.parse_args()
    _require_database_url()
    try:
        return asyncio.run(run_checklist(pending_limit=max(1, args.pending_limit), as_json=args.json))
    except Exception as exc:
        logger.error("outbox triage checklist failed", error=str(exc))
        print(json.dumps({"error": str(exc)}, ensure_ascii=False))
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
