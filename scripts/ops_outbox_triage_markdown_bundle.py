"""Print combined markdown operator triage bundle (read-only, no sends)."""

from __future__ import annotations

import argparse
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PY = os.path.join(ROOT, ".venv", "bin", "python")
if not os.path.isfile(PY):
    PY = sys.executable


def _env() -> dict[str, str]:
    working = os.environ.get("JOBPILOT_WORKING_DATABASE_URL") or os.environ.get("DATABASE_URL")
    if not working:
        print("Set JOBPILOT_WORKING_DATABASE_URL", file=sys.stderr)
        raise SystemExit(2)
    env = {**os.environ, "PYTHONPATH": ROOT, "DATABASE_URL": working}
    env["JOBPILOT_WORKING_DATABASE_URL"] = os.environ.get("JOBPILOT_WORKING_DATABASE_URL") or working
    return env


def _run(script: str, *args: str) -> str:
    proc = subprocess.run(
        [PY, os.path.join(ROOT, "scripts", script), *args],
        cwd=ROOT,
        env=_env(),
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        raise RuntimeError(proc.stderr or proc.stdout or script)
    return proc.stdout


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args()
    pre = subprocess.run(
        [PY, os.path.join(ROOT, "scripts", "ops_working_db_preflight.py")],
        cwd=ROOT,
        env=_env(),
        capture_output=True,
        text=True,
    )
    if pre.returncode != 0:
        sys.stderr.write(pre.stdout or pre.stderr or "preflight failed")
        return pre.returncode or 1
    parts = [
        "# JobPilot outbox operator triage bundle",
        "",
        "## Working DB preflight",
        "",
        "```json",
        pre.stdout.strip(),
        "```",
        "",
        _run("ops_outbox_triage_priority.py"),
        _run("ops_outbox_p1_timeout_checklist.py"),
        _run("ops_outbox_p1_timeout_checklist.py", "--error-bucket", "other"),
        _run("ops_outbox_p2_active_pending_checklist.py"),
        _run("ops_outbox_inbox_na_checklist.py"),
        "---",
        "Generated by `scripts/ops_outbox_triage_markdown_bundle.py`",
    ]
    print("\n".join(parts))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
